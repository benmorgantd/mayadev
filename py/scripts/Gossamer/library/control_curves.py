def scale_control(control, factor):
  # scale the control cvs by the specified factor
  cmds.hilite(control)
  cmds.select(control + ".cv[0:]")
  cmds.scale(factor, factor, factor)
  cmds.select(control)
  cmds.select(cl=1)
